import torch
import torch.nn as nn

from torch.utils.data import TensorDataset, DataLoader

class GLNet(nn.Module):

    def __init__(self, input_dim):

        super().__init__()

        self.feature_layer = nn.Linear(input_dim, 64)

        self.gate = nn.Sequential(
            nn.Linear(64, 64),
            nn.Sigmoid()
        )

        self.classifier = nn.Sequential(
            nn.Linear(64, 32),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(32, 1)
        )

    def forward(self, x):

        features = torch.relu(
            self.feature_layer(x)
        )

        gate = self.gate(features)

        gated_features = features * gate

        return self.classifier(
            gated_features
        ).squeeze(1)

def train_glnet(X, y, epochs=20):

    X = torch.tensor(
        np.asarray(X),
        dtype=torch.float32
    )

    y = torch.tensor(
        np.asarray(y),
        dtype=torch.float32
    )

    dataset = TensorDataset(X, y)

    loader = DataLoader(
        dataset,
        batch_size=128,
        shuffle=True
    )

    model = GLNet(X.shape[1])

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=0.001
    )

    loss_function = nn.BCEWithLogitsLoss()

    for epoch in range(epochs):

        model.train()

        for batch_X, batch_y in loader:

            optimizer.zero_grad()

            output = model(batch_X)

            loss = loss_function(
                output,
                batch_y
            )

            loss.backward()

            optimizer.step()

    return model

def predict_glnet(model, X):

    model.eval()

    X = torch.tensor(
        np.asarray(X),
        dtype=torch.float32
    )

    with torch.no_grad():

        probabilities = torch.sigmoid(
            model(X)
        )

    return probabilities.numpy()

