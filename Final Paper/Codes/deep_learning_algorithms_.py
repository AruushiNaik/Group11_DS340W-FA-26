class MambaLayer(nn.Module):

    def __init__(self, d_model, d_state=8):
        super().__init__()

        self.d_model = d_model
        self.d_state = d_state

        self.norm = nn.LayerNorm(d_model)

        self.in_proj = nn.Linear(d_model, d_model * 2)

        self.x_proj = nn.Linear(
            d_model,
            d_model + 2 * d_state
        )

        self.dt_proj = nn.Linear(d_model, d_model)

        self.A_log = nn.Parameter(
            torch.randn(d_model, d_state) * 0.1
        )

        self.D = nn.Parameter(torch.ones(d_model))

        self.out_proj = nn.Linear(d_model, d_model)

    def forward(self, x):

        residual = x
        x = self.norm(x)

        # Input and gating projections
        xz = self.in_proj(x)
        x_input, z = xz.chunk(2, dim=-1)

        # Input-dependent state parameters
        projected = self.x_proj(x_input)

        dt_input, B, C = torch.split(
            projected,
            [self.d_model, self.d_state, self.d_state],
            dim=-1
        )

        dt = F.softplus(self.dt_proj(dt_input)) + 1e-4

        # Negative state transition matrix
        A = -torch.exp(self.A_log)

        batch_size, seq_len, _ = x_input.shape

        state = torch.zeros(
            batch_size,
            self.d_model,
            self.d_state,
            device=x.device
        )

        outputs = []

        # Selective state-space scan
        for t in range(seq_len):

            dt_t = dt[:, t, :]
            B_t = B[:, t, :]
            C_t = C[:, t, :]
            x_t = x_input[:, t, :]

            dA = torch.exp(
                dt_t.unsqueeze(-1) * A.unsqueeze(0)
            )

            dB = (
                dt_t.unsqueeze(-1)
                * B_t.unsqueeze(1)
                * x_t.unsqueeze(-1)
            )

            state = dA * state + dB

            y = torch.sum(
                state * C_t.unsqueeze(1),
                dim=-1
            )

            y = y + self.D * x_t

            outputs.append(y)

        output = torch.stack(outputs, dim=1)

        # Gating
        output = output * F.silu(z)

        output = self.out_proj(output)

        return output + residual

class GLNetMamba(nn.Module):

    def __init__(
        self,
        n_features,
        d_model=32,
        d_state=8,
        n_layers=2
    ):
        super().__init__()

        # Project individual features into embeddings
        self.feature_projection = nn.Linear(1, d_model)

        # Learnable feature embeddings
        self.feature_embedding = nn.Parameter(
            torch.randn(1, n_features, d_model) * 0.02
        )

        # GLNet gating
        self.gate_linear = nn.Linear(d_model, d_model)
        self.value_linear = nn.Linear(d_model, d_model)

        # Mamba layers
        self.mamba_layers = nn.ModuleList([
            MambaLayer(d_model, d_state)
            for _ in range(n_layers)
        ])

        self.norm = nn.LayerNorm(d_model)

        # Classification head
        self.classifier = nn.Sequential(
            nn.Linear(d_model, 32),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(32, 1)
        )

    def forward(self, x):

        # Convert tabular features into feature tokens
        x = x.unsqueeze(-1)

        x = self.feature_projection(x)

        x = x + self.feature_embedding

        # Gated feature interaction
        gate = torch.sigmoid(self.gate_linear(x))
        value = F.silu(self.value_linear(x))

        x = gate * value + x

        # Mamba processing
        for layer in self.mamba_layers:
            x = layer(x)

        x = self.norm(x)

        # Mean pooling across features
        x = x.mean(dim=1)

        # Binary classification logits
        return self.classifier(x)

