# Wrapper to prevent .squeeze(1) from removing the output dimension which crashes DeepExplainer
class SHAPWrapper(torch.nn.Module):
    def __init__(self, model):
        super().__init__()
        self.model = model

    def forward(self, x):
        out = self.model(x)
        if out.ndim == 1:
            return out.unsqueeze(1)
        return out

# Instantiate the wrapper
shap_friendly_model = SHAPWrapper(final_glnet)

# Create DeepExplainer using the wrapped model
explainer = shap.DeepExplainer(
    shap_friendly_model,
    background_tensor
)

# Calculate SHAP values for 1,000 observations (disabling strict additivity checks)
shap_values = explainer.shap_values(
    test_tensor,
    check_additivity=False
)

# Handle different SHAP output formats
if isinstance(shap_values, list):
    shap_values = shap_values[0]

shap_values = np.asarray(shap_values)

# Remove unnecessary output dimension if present
if shap_values.ndim == 3:
    shap_values = shap_values[:, :, 0]

