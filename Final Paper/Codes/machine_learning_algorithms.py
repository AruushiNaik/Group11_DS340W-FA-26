## DATAPROCESSING AND QUALITY CHECKS

# Load the three separate datasets
train = pd.read_csv("train.csv")
test = pd.read_csv("test.csv")
validation = pd.read_csv("validation.csv")

# Separate features and target variable
X_train = train.drop("Depression", axis=1)
y_train = train["Depression"]

X_test = test.drop("Depression", axis=1)
y_test = test["Depression"]

X_val = validation.drop("Depression", axis=1)
y_val = validation["Depression"]


## DATAPROCESSING AND QUALITY CHECKS

# Missing values
print("Missing values in Training data:")
print(X_train.isnull().sum())

print("\nMissing values in Test data:")
print(X_test.isnull().sum())

print("\nMissing values in Validation data:")
print(X_val.isnull().sum())


# Duplicate rows
print("\nDuplicate rows in Training data:", X_train.duplicated().sum())
print("Duplicate rows in Test data:", X_test.duplicated().sum())
print("Duplicate rows in Validation data:", X_val.duplicated().sum())


# Remove duplicate rows from each dataset
duplicate_rows_train = X_train.index[X_train.duplicated()]
X_train = X_train.drop(index=duplicate_rows_train)
y_train = y_train.loc[X_train.index]

duplicate_rows_test = X_test.index[X_test.duplicated()]
X_test = X_test.drop(index=duplicate_rows_test)
y_test = y_test.loc[X_test.index]

duplicate_rows_val = X_val.index[X_val.duplicated()]
X_val = X_val.drop(index=duplicate_rows_val)
y_val = y_val.loc[X_val.index]


# Outlier check using the IQR method (numeric columns)
numeric_columns = X_train.select_dtypes(include=np.number).columns

for column in numeric_columns:
    Q1 = X_train[column].quantile(0.25)
    Q3 = X_train[column].quantile(0.75)
    IQR = Q3 - Q1

    lower_limit = Q1 - 1.5 * IQR
    upper_limit = Q3 + 1.5 * IQR

    print(column, "Outliers:",
          ((X_train[column] < lower_limit) |
           (X_train[column] > upper_limit)).sum())

print("\nData Processing and Quality Checks Completed")

# Separate numeric and categorical columns
numeric_columns = X_train.select_dtypes(include=np.number).columns
categorical_columns = X_train.select_dtypes(exclude=np.number).columns

# Missing value treatment: fit on training data only
numeric_imputer = SimpleImputer(strategy="median")
categorical_imputer = SimpleImputer(strategy="most_frequent")

X_train[numeric_columns] = numeric_imputer.fit_transform(X_train[numeric_columns])
X_test[numeric_columns] = numeric_imputer.transform(X_test[numeric_columns])
X_val[numeric_columns] = numeric_imputer.transform(X_val[numeric_columns])

if len(categorical_columns) > 0:
    X_train[categorical_columns] = categorical_imputer.fit_transform(X_train[categorical_columns])
    X_test[categorical_columns] = categorical_imputer.transform(X_test[categorical_columns])
    X_val[categorical_columns] = categorical_imputer.transform(X_val[categorical_columns])

# Encoding categorical variables
X_train = pd.get_dummies(X_train, columns=categorical_columns)
X_test = pd.get_dummies(X_test, columns=categorical_columns)
X_val = pd.get_dummies(X_val, columns=categorical_columns)

# Make test and validation columns match training columns
X_test = X_test.reindex(columns=X_train.columns, fill_value=0)
X_val = X_val.reindex(columns=X_train.columns, fill_value=0)

# Scaling: fit on training data only
sc = MinMaxScaler()
X_train = pd.DataFrame(sc.fit_transform(X_train), columns=X_train.columns, index=X_train.index)
X_test = pd.DataFrame(sc.transform(X_test), columns=X_test.columns, index=X_test.index)
X_val = pd.DataFrame(sc.transform(X_val), columns=X_val.columns, index=X_val.index)

print("Preprocessing completed")

## SMOTE ON TRAINING DATA

print("Class distribution before SMOTE:")
print(y_train.value_counts())

sm = SMOTE(random_state=1)
X_train_smote, y_train_smote = sm.fit_resample(X_train, y_train)

print("Class distribution after SMOTE:")
print(pd.Series(y_train_smote).value_counts())

## T-TEST

# t-test for numeric predictors against a binary target
t_test_results = []

for column in X_train.select_dtypes(include=np.number).columns:
    group_0 = X_train.loc[np.asarray(y_train) == 0, column]
    group_1 = X_train.loc[np.asarray(y_train) == 1, column]

    t_stat, p_value = ttest_ind(group_0, group_1, equal_var=False, nan_policy="omit")
    t_test_results.append([column, t_stat, p_value])

t_test_df = pd.DataFrame(t_test_results, columns=["Feature", "T-Statistic", "P-Value"])
t_test_df = t_test_df.sort_values("P-Value")
t_test_df

## FEATURE SELECTION - RFE

np.random.seed(1)

rfe_model = LogisticRegression(max_iter=1000)
rfe = RFE(estimator=rfe_model, n_features_to_select=min(15, X_train_smote.shape[1]))
rfe.fit(X_train_smote, y_train_smote)

selected_features = X_train_smote.columns[rfe.support_]
print("Selected Features:")
print(selected_features)

X_train_selected = X_train_smote[selected_features]
X_test_selected = X_test[selected_features]
X_val_selected = X_val[selected_features]

## STRATIFIED CROSS VALIDATION + EVALUATION METRICS

kf = StratifiedKFold(n_splits=5, shuffle=True, random_state=1)

def specificity_score(y_true, y_pred):
    cm = confusion_matrix(y_true, y_pred, labels=[0, 1])
    tn, fp, fn, tp = cm.ravel()
    return tn / (tn + fp) if (tn + fp) > 0 else 0

scoring = {
    "accuracy": "accuracy",
    "precision": "precision_weighted",
    "recall": "recall_weighted",
    "f1": "f1_weighted",
    "auc": "roc_auc",
    "specificity": make_scorer(specificity_score)
}

## TRADITIONAL ML

models = {
    "Random Forest": RandomForestClassifier(random_state=1),
    "XGBoost": XGBClassifier(random_state=1, eval_metric="logloss"),
    "LightGBM": lgb.LGBMClassifier(random_state=1, verbosity=-1),
    # Linear SVM is far faster than SVC(kernel="rbf") on ~100K rows.
    # CalibratedClassifierCV adds predict_proba so AUC still works.
    "SVM": CalibratedClassifierCV(LinearSVC(random_state=1, max_iter=5000), cv=3),
    "Logistic Regression": LogisticRegression(max_iter=1000, random_state=1),
    "CatBoost": CatBoostClassifier(verbose=0, random_seed=1),
    "KNN": KNeighborsClassifier(),
    "Gaussian Naive Bayes": GaussianNB()
}

model_results = []

for model_name, model in models.items():
    print("Model:", model_name)

    model_pipeline = Pipeline([
        ("smote", SMOTE(random_state=1)),
        ("model", model)
    ])

    cv_results = cross_validate(
        model_pipeline,
        X_train[selected_features],
        y_train,
        cv=kf,
        scoring=scoring,
        n_jobs=-1
    )

    model_pipeline.fit(X_train[selected_features], y_train)

    pred_test = model_pipeline.predict(X_test[selected_features])
    pred_proba = model_pipeline.predict_proba(X_test[selected_features])[:, 1]

    accur = accuracy_score(y_test, pred_test)
    prec = precision_score(y_test, pred_test, average="weighted", zero_division=0)
    rec = recall_score(y_test, pred_test, average="weighted", zero_division=0)
    f1 = f1_score(y_test, pred_test, average="weighted", zero_division=0)
    auc = roc_auc_score(y_test, pred_proba)
    specificity = specificity_score(y_test, pred_test)

    print("Confusion Matrix:")
    print(confusion_matrix(y_test, pred_test))
    print("Accuracy:", accur)
    print("Precision:", prec)
    print("Recall:", rec)
    print("F1 Score:", f1)
    print("AUC:", auc)
    print("Specificity:", specificity)

    model_results.append([
        model_name,
        np.mean(cv_results["test_accuracy"]),
        np.mean(cv_results["test_precision"]),
        np.mean(cv_results["test_recall"]),
        np.mean(cv_results["test_f1"]),
        np.mean(cv_results["test_auc"]),
        np.mean(cv_results["test_specificity"]),
        accur, prec, rec, f1, auc, specificity
    ])

model_results_df = pd.DataFrame(model_results, columns=[
    "Model", "CV Accuracy", "CV Precision", "CV Recall", "CV F1",
    "CV AUC", "CV Specificity", "Test Accuracy", "Test Precision",
    "Test Recall", "Test F1", "Test AUC", "Test Specificity"
])
model_results_df

