def train_glnet(
    X_data,
    y_data,
    epochs=20,
    batch_size=128
):

    X_tensor = torch.tensor(
        np.asarray(X_data),
        dtype=torch.float32
    )

    y_tensor = torch.tensor(
        np.asarray(y_data),
        dtype=torch.float32
    ).reshape(-1, 1)

    dataset = TensorDataset(
        X_tensor,
        y_tensor
    )

    # Reproducible DataLoader shuffling
    generator = torch.Generator()
    generator.manual_seed(SEED)

    loader = DataLoader(
    dataset,
    batch_size=batch_size,
    shuffle=True,
    generator=generator
    )

    model = GLNetMamba(
        n_features=X_data.shape[1],
        d_model=32,
        d_state=8,
        n_layers=2
    ).to(device)

    criterion = nn.BCEWithLogitsLoss()

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=0.001,
        weight_decay=0.0001
    )

    for epoch in range(epochs):

        model.train()

        total_loss = 0

        for X_batch, y_batch in loader:

            X_batch = X_batch.to(device)
            y_batch = y_batch.to(device)

            optimizer.zero_grad()

            outputs = model(X_batch)

            loss = criterion(
                outputs,
                y_batch
            )

            loss.backward()

            optimizer.step()

            total_loss += loss.item()

        avg_loss = total_loss / len(loader)

        print(
            f"Epoch [{epoch + 1}/{epochs}] "
            f"Loss: {avg_loss:.4f}"
        )

    return model


def predict_glnet(model, X_data):

    model.eval()

    X_tensor = torch.tensor(
        np.asarray(X_data),
        dtype=torch.float32
    ).to(device)

    with torch.no_grad():

        logits = model(X_tensor)

        probabilities = torch.sigmoid(
            logits
        ).cpu().numpy().flatten()

    return probabilities


