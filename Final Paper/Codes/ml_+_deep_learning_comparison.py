best_pipeline = fitted_models[best_model_name]
trained_model = best_pipeline.named_steps["model"]

# 3. Select up to 1000 validation observations
X_shap = X_val[selected_features].sample(
    n=min(1000, len(X_val)),
    random_state=42
)

print("Number of SHAP observations:", len(X_shap))

# 4. Select background observations from training data
X_background = X_train[selected_features].sample(
    n=min(100, len(X_train)),
    random_state=42
)

# 5. Create output folder
os.makedirs("SHAP_Outputs", exist_ok=True)

# 6. Select appropriate SHAP explainer
model_type = type(trained_model).__name__.lower()

if any(name in model_type for name in
       ["randomforest", "xgb", "lgbm", "catboost", "gradientboosting"]):

    print("Using TreeExplainer")
    explainer = shap.TreeExplainer(trained_model)

    try:
        shap_values = explainer(
            X_shap,
            check_additivity=False
        )
    except TypeError:
        shap_values = explainer(X_shap)

elif "logisticregression" in model_type:

    print("Using LinearExplainer")
    explainer = shap.LinearExplainer(
        trained_model,
        X_background
    )
    shap_values = explainer(X_shap)

else:

    print("Using Permutation Explainer")
    explainer = shap.Explainer(
        trained_model.predict_proba,
        X_background,
        algorithm="permutation"
    )

    shap_values = explainer(
        X_shap,
        max_evals=2 * len(selected_features) + 1
    )

# 7. Extract positive-class SHAP values (Depression = 1)
if isinstance(shap_values, list):
    values = shap_values[1]
    base_values = explainer.expected_value
    if np.ndim(base_values) > 0:
        base_values = base_values[1]

else:
    values = shap_values.values
    base_values = shap_values.base_values

    if values.ndim == 3:
        values = values[:, :, 1]

        if np.ndim(base_values) == 2:
            base_values = base_values[:, 1]

# Create a consistent SHAP Explanation object
shap_values_positive = shap.Explanation(
    values=values,
    base_values=base_values,
    data=X_shap.to_numpy(),
    feature_names=list(X_shap.columns)
)

