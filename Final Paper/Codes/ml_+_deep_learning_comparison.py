# Remove duplicate rows from each dataset
duplicate_rows_train = X_train.index[X_train.duplicated()]
X_train = X_train.drop(index=duplicate_rows_train)
y_train = y_train.loc[X_train.index]

duplicate_rows_test = X_test.index[X_test.duplicated()]
X_test = X_test.drop(index=duplicate_rows_test)
y_test = y_test.loc[X_test.index]

duplicate_rows_val = X_val.index[X_val.duplicated()]
X_val = X_val.drop(index=duplicate_rows_val)
y_val = y_val.loc[X_val.index]


# Outlier check using the IQR method (numeric columns)
numeric_columns = X_train.select_dtypes(include=np.number).columns

for column in numeric_columns:
    Q1 = X_train[column].quantile(0.25)
    Q3 = X_train[column].quantile(0.75)
    IQR = Q3 - Q1

    lower_limit = Q1 - 1.5 * IQR
    upper_limit = Q3 + 1.5 * IQR

    print(column, "Outliers:",
          ((X_train[column] < lower_limit) |
           (X_train[column] > upper_limit)).sum())

print("\nData Processing and Quality Checks Completed")

# Separate numeric and categorical columns
numeric_columns = X_train.select_dtypes(include=np.number).columns
categorical_columns = X_train.select_dtypes(exclude=np.number).columns

# Missing value treatment: fit on training data only
numeric_imputer = SimpleImputer(strategy="median")
categorical_imputer = SimpleImputer(strategy="most_frequent")

X_train[numeric_columns] = numeric_imputer.fit_transform(X_train[numeric_columns])
X_test[numeric_columns] = numeric_imputer.transform(X_test[numeric_columns])
X_val[numeric_columns] = numeric_imputer.transform(X_val[numeric_columns])

if len(categorical_columns) > 0:
    X_train[categorical_columns] = categorical_imputer.fit_transform(X_train[categorical_columns])
    X_test[categorical_columns] = categorical_imputer.transform(X_test[categorical_columns])
    X_val[categorical_columns] = categorical_imputer.transform(X_val[categorical_columns])

# Encoding categorical variables
X_train = pd.get_dummies(X_train, columns=categorical_columns)
X_test = pd.get_dummies(X_test, columns=categorical_columns)
X_val = pd.get_dummies(X_val, columns=categorical_columns)

# Make test and validation columns match training columns
X_test = X_test.reindex(columns=X_train.columns, fill_value=0)
X_val = X_val.reindex(columns=X_train.columns, fill_value=0)

# Scaling: fit on training data only
sc = MinMaxScaler()
X_train = pd.DataFrame(sc.fit_transform(X_train), columns=X_train.columns, index=X_train.index)
X_test = pd.DataFrame(sc.transform(X_test), columns=X_test.columns, index=X_test.index)
X_val = pd.DataFrame(sc.transform(X_val), columns=X_val.columns, index=X_val.index)

