## T-TEST

# t-test for numeric predictors against a binary target
t_test_results = []

for column in X_train.select_dtypes(include=np.number).columns:
    group_0 = X_train.loc[np.asarray(y_train) == 0, column]
    group_1 = X_train.loc[np.asarray(y_train) == 1, column]

    t_stat, p_value = ttest_ind(group_0, group_1, equal_var=False, nan_policy="omit")
    t_test_results.append([column, t_stat, p_value])

t_test_df = pd.DataFrame(t_test_results, columns=["Feature", "T-Statistic", "P-Value"])
t_test_df = t_test_df.sort_values("P-Value")
