# BENCHMARKING PIPELINE
# ==========================================
class MLBenchmarkingPipeline:
    def __init__(self, X, y, categorical_cols=None, numerical_cols=None):
        self.X = X
        self.y = y
        self.categorical_cols = categorical_cols if categorical_cols else []
        self.numerical_cols = numerical_cols if numerical_cols else X.select_dtypes(include=[np.number]).columns.tolist()
        self.results = []
        self.trained_models = {}

    def preprocess_data(self):
        print("[INFO] Preprocessing data (Imputation, Encoding, Scaling)...")
        X_train, X_test, y_train, y_test = train_test_split(
            self.X, self.y, test_size=0.2, random_state=42, stratify=self.y
        )

        num_transformer = Pipeline(steps=[
            ('imputer', SimpleImputer(strategy='median')),
            ('scaler', StandardScaler())
        ])

        cat_transformer = Pipeline(steps=[
            ('imputer', SimpleImputer(strategy='most_frequent')),
            ('onehot', OneHotEncoder(handle_unknown='ignore', sparse_output=False))
        ])

        preprocessor = ColumnTransformer(
            transformers=[
                ('num', num_transformer, self.numerical_cols),
                ('cat', cat_transformer, self.categorical_cols)
            ]
        )

        X_train_prep = preprocessor.fit_transform(X_train)
        X_test_prep = preprocessor.transform(X_test)

        return X_train_prep, X_test_prep, y_train, y_test

    def apply_feature_selection(self, X_train, y_train, X_test, method='correlation', k=10):
        print(f"[INFO] Applying feature selection: {method}")

        if method == 'correlation':
            df_train = pd.DataFrame(X_train)
            corr_matrix = df_train.corr().abs()
            upper_tri = corr_matrix.where(np.triu(np.ones(corr_matrix.shape), k=1).astype(bool))
            to_drop = [column for column in upper_tri.columns if any(upper_tri[column] > 0.85)]
            selected_features = [i for i in range(X_train.shape[1]) if i not in to_drop]
            return X_train[:, selected_features], X_test[:, selected_features]

        elif method == 'chi2':
            scaler_pos = MinMaxScaler()
            X_train_pos = scaler_pos.fit_transform(X_train)
            X_test_pos = scaler_pos.transform(X_test)

            selector = SelectKBest(score_func=chi2, k=min(k, X_train.shape[1]))
            X_train_sel = selector.fit_transform(X_train_pos, y_train)
            X_test_sel = selector.transform(X_test_pos)
            return X_train_sel, X_test_sel

        elif method == 'rfe':
            estimator = LogisticRegression(max_iter=1000, random_state=42)
            selector = RFE(estimator, n_features_to_select=min(k, X_train.shape[1]), step=1)
            X_train_sel = selector.fit_transform(X_train, y_train)
            X_test_sel = selector.transform(X_test)
            return X_train_sel, X_test_sel

        elif method == 'pca':
            pca = PCA(n_components=min(k, X_train.shape[1]), random_state=42)
            X_train_sel = pca.fit_transform(X_train)
            X_test_sel = pca.transform(X_test)
            return X_train_sel, X_test_sel

        elif method == 'sparse_pca':
            spca = SparsePCA(n_components=min(k, X_train.shape[1]), random_state=42, max_iter=500)
            X_train_sel = spca.fit_transform(X_train)
            X_test_sel = spca.transform(X_test)
            return X_train_sel, X_test_sel

        else:
            return X_train, X_test

    def get_models(self):
        return {
            'Gaussian Naive Bayes': GaussianNB(),
            'Logistic Regression': LogisticRegression(max_iter=1000, random_state=42),
            'Random Forest': RandomForestClassifier(random_state=42),
            'SVM': SVC(probability=True, random_state=42),
            'LightGBM': LGBMClassifier(random_state=42, verbose=-1),
            'MLP': MLPClassifier(random_state=42, max_iter=500),
            'CatBoost': CatBoostClassifier(verbose=0, random_state=42),
            'KNN': KNeighborsClassifier(),
            'XGBoost': XGBClassifier(eval_metric='logloss', random_state=42),
            'GLNet (Mamba+CNN)': GLNetClassifier(random_state=42)
        }

    def evaluate_metrics(self, y_true, y_pred, y_prob):
        cm = confusion_matrix(y_true, y_pred)
        tn, fp, fn, tp = cm.ravel() if cm.shape == (2, 2) else (0, 0, 0, 0)

        accuracy = accuracy_score(y_true, y_pred)
        precision = precision_score(y_true, y_pred, zero_division=0)
        recall = recall_score(y_true, y_pred, zero_division=0)
        specificity = tn / (tn + fp) if (tn + fp) > 0 else 0
        f1 = f1_score(y_true, y_pred, zero_division=0)

        try:
            roc_auc = roc_auc_score(y_true, y_prob)
        except ValueError:
            roc_auc = 0.0

        return {
            'Accuracy': accuracy,
            'Precision': precision,
            'Recall': recall,
            'Specificity': specificity,
            'F1-Score': f1,
            'ROC-AUC': roc_auc,
            'Confusion Matrix': cm
        }

    def run_pipeline(self):
        X_train_prep, X_test_prep, y_train, y_test = self.preprocess_data()
        fs_methods = ['correlation', 'chi2', 'rfe', 'pca', 'sparse_pca']
        models = self.get_models()

        for fs_method in fs_methods:
            print(f"\n--- Running Feature Selection: {fs_method.upper()} ---")
            X_train_fs, X_test_fs = self.apply_feature_selection(
                X_train_prep, y_train, X_test_prep, method=fs_method, k=10
            )

            # Apply SMOTE strictly to training partitions
            smote = SMOTE(random_state=42)
            X_train_smote, y_train_smote = smote.fit_resample(X_train_fs, y_train)

            for model_name, model in models.items():
                print(f"Training {model_name}...")
                try:
                    model.fit(X_train_smote, y_train_smote)

                    y_pred = model.predict(X_test_fs)
                    y_prob = model.predict_proba(X_test_fs)[:, 1] if hasattr(model, "predict_proba") else np.zeros_like(y_pred, dtype=float)

                    metrics = self.evaluate_metrics(y_test, y_pred, y_prob)

                    record = {
                        'Feature Selection': fs_method,
                        'Model': model_name,
                        **{k: v for k, v in metrics.items() if k != 'Confusion Matrix'}
                    }
                    self.results.append(record)
                    self.trained_models[(fs_method, model_name)] = {
                        'model': model,
                        'X_test': X_test_fs,
                        'confusion_matrix': metrics['Confusion Matrix']
                    }
                except Exception as e:
                    print(f"Error training {model_name} with {fs_method}: {e}")

    def get_summary_dataframe(self):
        df_results = pd.DataFrame(self.results)
        if not df_results.empty:
            df_results = df_results.sort_values(by='ROC-AUC', ascending=False).reset_index(drop=True)
        return df_results

    def compute_shap_for_best(self, best_fs, best_model_name):
        print(f"\n[INFO] Computing SHAP values for: {best_fs} + {best_model_name}")
        key = (best_fs, best_model_name)
        if key not in self.trained_models:
            print("Model configuration not found.")
            return

        model_obj = self.trained_models[key]['model']
        X_test_data = self.trained_models[key]['X_test']

        try:
            if isinstance(model_obj, (RandomForestClassifier, LGBMClassifier, XGBClassifier, CatBoostClassifier)):
                explainer = shap.TreeExplainer(model_obj)
                shap_values = explainer.shap_values(X_test_data)
            else:
                background = X_test_data[np.random.choice(X_test_data.shape[0], min(50, X_test_data.shape[0]), replace=False)]
                explainer = shap.KernelExplainer(model_obj.predict_proba, background)
                shap_values = explainer.shap_values(X_test_data)

            shap.summary_plot(shap_values, X_test_data, show=True)
        except Exception as e:
            print(f"Could not compute SHAP directly: {e}")

