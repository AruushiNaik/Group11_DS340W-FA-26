# GLNet ARCHITECTURE (Mamba + Convolutional)
# ==========================================
class GLNetBlock(nn.Module):
    """Global and Local Block (GLB) combining 1D convolution and Mamba-inspired sequence projections."""
    def __init__(self, channels):
        super(GLNetBlock, self).__init__()
        self.conv = nn.Conv1d(in_channels=channels, out_channels=channels, kernel_size=3, padding=1)
        self.bn = nn.BatchNorm1d(channels)
        self.activation = nn.LeakyReLU()
        self.mamba_proj = nn.Linear(channels, channels)

    def forward(self, x):
        res = x
        out = self.conv(x)
        out = self.bn(out)
        out = self.activation(out)

        # Linear/Mamba-style projection across feature dimensions
        out = out.permute(0, 2, 1)
        out = self.mamba_proj(out)
        out = out.permute(0, 2, 1)

        return out + res

class GLNet(nn.Module):
    """GLNet: Integrates convolutional and Mamba layers for robust feature processing."""
    def __init__(self, input_dim, hidden_dim=128):
        super(GLNet, self).__init__()
        self.fc_in = nn.Linear(input_dim, hidden_dim)
        self.glb1 = GLNetBlock(hidden_dim)
        self.glb2 = GLNetBlock(hidden_dim)

        self.classifier = nn.Sequential(
            nn.AdaptiveAvgPool1d(1),
            nn.Flatten(),
            nn.Linear(hidden_dim, 64),
            nn.ReLU(),
            nn.Linear(64, 2)
        )

    def forward(self, x):
        x = self.fc_in(x)
        x = x.unsqueeze(2) # Reshape for 1D Convolution
        x = self.glb1(x)
        x = self.glb2(x)
        logits = self.classifier(x)
        return logits

class GLNetClassifier(BaseEstimator, ClassifierMixin):
    """Scikit-learn compatible wrapper for GLNet."""
    def __init__(self, hidden_dim=128, epochs=15, batch_size=32, lr=0.001, random_state=42):
        self.hidden_dim = hidden_dim
        self.epochs = epochs
        self.batch_size = batch_size
        self.lr = lr
        self.random_state = random_state
        self.model = None
        self.classes_ = np.array([0, 1])

    def fit(self, X, y):
        torch.manual_seed(self.random_state)
        n_features = X.shape[1]
        self.model = GLNet(input_dim=n_features, hidden_dim=self.hidden_dim)
        optimizer = optim.Adam(self.model.parameters(), lr=self.lr)
        criterion = nn.CrossEntropyLoss()

        X_tensor = torch.tensor(X, dtype=torch.float32)
        y_tensor = torch.tensor(y, dtype=torch.long)
        dataset = TensorDataset(X_tensor, y_tensor)
        loader = DataLoader(dataset, batch_size=self.batch_size, shuffle=True)

        self.model.train()
        for epoch in range(self.epochs):
            for batch_X, batch_y in loader:
                optimizer.zero_grad()
                outputs = self.model(batch_X)
                loss = criterion(outputs, batch_y)
                loss.backward()
                optimizer.step()
        return self

    def predict(self, X):
        probs = self.predict_proba(X)
        return np.argmax(probs, axis=1)

    def predict_proba(self, X):
        self.model.eval()
        X_tensor = torch.tensor(X, dtype=torch.float32)
        with torch.no_grad():
            outputs = self.model(X_tensor)
            probs = torch.softmax(outputs, dim=1).numpy()
        return probs

