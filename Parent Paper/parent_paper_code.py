import warnings
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import shap
from scipy.stats import ttest_ind
from sklearn.preprocessing import StandardScaler, MinMaxScaler
from sklearn.feature_selection import SelectKBest, f_classif, chi2
from sklearn.model_selection import StratifiedKFold
from sklearn.ensemble import RandomForestClassifier
from sklearn.svm import SVC
from sklearn.metrics import (accuracy_score, precision_score, recall_score,
                             f1_score, roc_auc_score, roc_curve)
from imblearn.over_sampling import SMOTE
from xgboost import XGBClassifier
from lightgbm import LGBMClassifier

warnings.filterwarnings("ignore")

# ----------------------------- SETTINGS -----------------------------
CSV_PATH = None          # None = download from Kaggle; or set a local path, e.g. "student.csv"
TARGET = None            # None = auto-detect the column with "depress" in its name; or type it exactly
K_FEATURES = 10          # number of features to keep
SAMPLE_ROWS = 10000      # SVM on 100k rows is very slow; use None to run on all rows
SEED = 42

# ------------------- 1. LOAD + PREPROCESS (missing, encoding) -------------------
if CSV_PATH is None:
    import glob, kagglehub
    folder = kagglehub.dataset_download("aldinwhyudii/student-depression-and-lifestyle-100k-data")
    CSV_PATH = glob.glob(f"{folder}/**/*.csv", recursive=True)[0]
df = pd.read_csv(CSV_PATH)
print("Columns:", list(df.columns))

if TARGET is None:
    TARGET = [c for c in df.columns if "depress" in c.lower()][0]
print("Target column:", TARGET)

df = df.drop(columns=[c for c in df.columns if c.lower() in ("id", "student_id")], errors="ignore")
df = df.dropna(subset=[TARGET])
if SAMPLE_ROWS and len(df) > SAMPLE_ROWS:   # stratified sample to keep runtime reasonable
    df = df.groupby(TARGET, group_keys=False).apply(
        lambda g: g.sample(int(SAMPLE_ROWS * len(g) / len(df)), random_state=SEED))

y = pd.factorize(df[TARGET], sort=True)[0]   # encode target to 0/1 (e.g. No=0, Yes=1)
X = df.drop(columns=[TARGET])

for col in X.columns:                    # missing values
    if X[col].dtype == "object":
        X[col] = X[col].fillna(X[col].mode()[0])
    else:
        X[col] = X[col].fillna(X[col].median())

X = pd.get_dummies(X, drop_first=True).astype(float)   # categorical encoding
K = min(K_FEATURES, X.shape[1])
print(f"Data: {X.shape[0]} rows, {X.shape[1]} features, class counts = {np.bincount(y)}")

# ------------------- 3. STATISTICAL TESTING (t-test, chi-square) -------------------
t_p = [ttest_ind(X[c][y == 0], X[c][y == 1], equal_var=False).pvalue for c in X.columns]
chi_scores, chi_p = chi2(MinMaxScaler().fit_transform(X), y)   # chi2 needs non-negative values
stats = pd.DataFrame({"t_test_p": t_p, "chi2_p": chi_p}, index=X.columns).sort_values("t_test_p")
print("\nStatistical tests (top 10 by t-test p-value):")
print(stats.head(10).round(5))

# ------------------- helper: scale + select + SMOTE (fit on training data only) -------------------
def prepare(X_train, y_train, X_test=None):
    scaler = StandardScaler().fit(X_train)                       # 1. StandardScaler
    selector = SelectKBest(f_classif, k=K).fit(scaler.transform(X_train), y_train)  # 2. feature selection
    Xtr = selector.transform(scaler.transform(X_train))
    Xte = selector.transform(scaler.transform(X_test)) if X_test is not None else None
    Xtr, ytr = SMOTE(random_state=SEED).fit_resample(Xtr, y_train)  # 4. SMOTE on training only
    return Xtr, ytr, Xte, selector

# ------------------- 5. MODELS -------------------
models = {
    "Random Forest": RandomForestClassifier(n_estimators=200, random_state=SEED),
    "XGBoost": XGBClassifier(n_estimators=200, eval_metric="logloss", random_state=SEED),
    "LightGBM": LGBMClassifier(n_estimators=200, random_state=SEED, verbose=-1),
    "SVM": SVC(probability=True, random_state=SEED),
}

# ------------------- 6 + 7. STRATIFIED 10-FOLD CV + EVALUATION -------------------
skf = StratifiedKFold(n_splits=10, shuffle=True, random_state=SEED)
results, oof_probs = {}, {}

for name, model in models.items():
    scores = {"Accuracy": [], "Precision": [], "Recall": [], "F1": [], "AUC": []}
    oof = np.zeros(len(y))
    for train_idx, test_idx in skf.split(X, y):
        Xtr, ytr, Xte, _ = prepare(X.iloc[train_idx], y[train_idx], X.iloc[test_idx])
        model.fit(Xtr, ytr)
        pred = model.predict(Xte)
        prob = model.predict_proba(Xte)[:, 1]
        oof[test_idx] = prob
        scores["Accuracy"].append(accuracy_score(y[test_idx], pred))
        scores["Precision"].append(precision_score(y[test_idx], pred, zero_division=0))
        scores["Recall"].append(recall_score(y[test_idx], pred))
        scores["F1"].append(f1_score(y[test_idx], pred))
        scores["AUC"].append(roc_auc_score(y[test_idx], prob))
    results[name] = {k: np.mean(v) for k, v in scores.items()}
    oof_probs[name] = oof
    print(f"\n{name}: " + ", ".join(f"{k}={v:.4f}" for k, v in results[name].items()))

results_df = pd.DataFrame(results).T
print("\n=== Model comparison (mean of 10 folds) ===")
print(results_df.round(4))

# best model = highest average of all five metrics
best_name = results_df.mean(axis=1).idxmax()
print(f"\nBest model: {best_name}")

# ------------------- 9. VISUALIZATIONS: ROC + model comparison -------------------
plt.figure(figsize=(6, 5))
for name, prob in oof_probs.items():
    fpr, tpr, _ = roc_curve(y, prob)
    plt.plot(fpr, tpr, label=f"{name} (AUC={roc_auc_score(y, prob):.3f})")
plt.plot([0, 1], [0, 1], "k--")
plt.xlabel("False Positive Rate"); plt.ylabel("True Positive Rate")
plt.title("ROC Curves (10-fold out-of-fold predictions)")
plt.legend(); plt.tight_layout(); plt.savefig("roc_curves.png", dpi=150); plt.show()

results_df.plot(kind="bar", figsize=(9, 5), ylim=(0, 1.05))
plt.title("Model Performance Comparison"); plt.ylabel("Score")
plt.xticks(rotation=0); plt.legend(loc="lower right")
plt.tight_layout(); plt.savefig("model_comparison.png", dpi=150); plt.show()

# ------------------- 8. EXPLAINABILITY: feature importance + SHAP (best model only) -------------------
Xtr, ytr, _, selector = prepare(X, y)                      # fit on all data for the final model
feat_names = X.columns[selector.get_support()]
Xtr = pd.DataFrame(Xtr, columns=feat_names)
best_model = models[best_name].fit(Xtr, ytr)

# feature importance (tree models only)
if hasattr(best_model, "feature_importances_"):
    imp = pd.Series(best_model.feature_importances_, index=feat_names).sort_values()
    imp.plot(kind="barh", figsize=(7, 5), title=f"Feature Importance - {best_name}")
    plt.tight_layout(); plt.savefig("feature_importance.png", dpi=150); plt.show()

# SHAP values
sample = Xtr.sample(min(100, len(Xtr)), random_state=SEED)
if best_name == "SVM":
    background = shap.sample(Xtr, 50, random_state=SEED)
    explainer = shap.KernelExplainer(lambda d: best_model.predict_proba(d)[:, 1], background)
    shap_values = explainer.shap_values(sample)
else:
    explainer = shap.TreeExplainer(best_model)
    shap_values = explainer.shap_values(sample)
    if isinstance(shap_values, list):          # older shap: list per class
        shap_values = shap_values[1]
    elif np.ndim(shap_values) == 3:            # newer shap: (samples, features, classes)
        shap_values = shap_values[:, :, 1]

# SHAP plots (only drawn because SHAP values exist)
shap.summary_plot(shap_values, sample, show=False)
plt.title(f"SHAP Summary - {best_name}"); plt.tight_layout()
plt.savefig("shap_summary.png", dpi=150); plt.show()

shap.summary_plot(shap_values, sample, plot_type="bar", show=False)
plt.title(f"SHAP Feature Importance - {best_name}"); plt.tight_layout()
plt.savefig("shap_bar.png", dpi=150); plt.show()